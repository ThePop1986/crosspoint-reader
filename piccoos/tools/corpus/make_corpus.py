#!/usr/bin/env python3
"""Generate the PiccoOS synthetic EPUB test corpus.

All text and cover art are generated by this script from built-in word lists,
so the corpus contains no third-party literary content. Output is deterministic
for a given --seed.

Usage:
    python3 make_corpus.py --out ./corpus [--seed 20261112] [--count 60]

Requires: Python 3.10+ and Pillow 12.3.0 (pinned in CI; Pillow 12 needs 3.10+).
Cover lettering uses the DejaVu Serif fonts bundled in ./fonts (Bitstream Vera
licence, see fonts/LICENSE-DejaVu.txt), so output does not depend on system fonts.

Reproducibility: same seed + same Pillow version + bundled fonts gives byte-identical
EPUBs (verified on Linux). Equality across operating systems is NOT yet verified;
compare against the sha256 values in manifest.json.
"""

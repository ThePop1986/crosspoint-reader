from xml.sax.saxutils import escape

if sys.version_info < (3, 10):
    sys.exit("Python 3.10+ is required")
try:
    import PIL
    from PIL import Image, ImageDraw, ImageFont
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required: pip install Pillow==12.3.0")

FONT_DIR = Path(__file__).resolve().parent / "fonts"
FONT_BOLD = FONT_DIR / "DejaVuSerif-Bold.ttf"
FONT_REGULAR = FONT_DIR / "DejaVuSerif.ttf"

# ---------------------------------------------------------------------------
# Word lists (common vocabulary; no copyrighted text)
# ---------------------------------------------------------------------------
RU_ADJ = ["Тихий", "Северный", "Последний", "Забытый", "Долгий", "Ясный", "Тёмный",
          "Старый", "Неизвестный", "Осенний", "Высокий", "Дальний", "Медленный"]
RU_NOUN = ["город", "берег", "сад", "маяк", "перевал", "архив", "вокзал", "остров",
           "дом", "лес", "мост", "колодец", "переулок", "горизонт"]
RU_LONG = ["Достопримечательности", "Человеконенавистничество", "Высокопревосходительство",
           "Электрификация", "Неудовлетворительность", "Взаимопонимание",
           "Переосвидетельствование", "Частнопредпринимательский", "Контрреволюционный"]
RU_PHRASE = ["и другие истории", "в двух частях", "и время перемен",
             "о котором никто не помнил", "записки наблюдателя", "по дороге домой",
             "в последний день лета", "и его обитатели", "между двумя войнами",
             "или путешествие на край карты"]
RU_SHORT = ["Сад", "Мост", "Дом", "Лёд", "Утро"]
EN_ADJ = ["Silent", "Northern", "Last", "Forgotten", "Distant", "Quiet", "Hidden", "Long"]
EN_NOUN = ["Harbor", "Garden", "Archive", "Station", "Island", "Bridge", "Valley", "Lighthouse"]
EN_PHRASE = ["and Other Stories", "of the Late Summer", "A Field Guide",
             "Notes from the Edge of the Map", "in Two Parts", "Revisited"]
RU_FIRST = ["Анна", "Пётр", "Мария", "Алексей", "Екатерина", "Дмитрий", "Ольга",
            "Сергей", "Наталья", "Игорь"]
# Surnames agree in gender with RU_FIRST at the same index (F, M, F, M, ...).
RU_LAST = ["Соколова", "Белов", "Кузнецова", "Орлов", "Воронцова", "Лебедев",
           "Громова", "Савельев", "Тихонова", "Миронов"]
EN_FIRST = ["Alice", "Thomas", "Grace", "Henry", "Clara"]
EN_LAST = ["Whitfield", "Marlow", "Ashby", "Penrose", "Calloway"]
RU_WORDS = ("утро вечер дорога окно ветер река письмо голос свет тень время город "
            "поле дождь снег память шаг дверь лампа книга карта поезд берег").split()
RU_VERBS = "шёл ждал помнил смотрел писал слушал искал видел знал думал".split()
EN_WORDS = ("morning evening road window wind river letter voice light shadow time city "
            "field rain snow memory step door lamp book map train shore").split()
EN_VERBS = "walked waited remembered watched wrote listened searched saw knew thought".split()

TRANSLIT = str.maketrans({
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "ts",
    "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu",
    "я": "ya"})


@dataclass
class BookSpec:
    index: int
    title: str
    title_kind: str          # ru_long | en | mixed | short
    language: str
    author: str | None
    author_file_as: str | None
    cover: str               # jpeg | jpeg_progressive | png | odd_square | odd_tall | none
    epub_version: str        # "2.0" | "3.0"
    series: str | None = None
    series_index: int | None = None
    chapters: int = 3
    filename: str = ""
    identifier: str = ""
    sha256: str = ""
    size: int = 0
    notes: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Spec planning
# ---------------------------------------------------------------------------
def make_title(rng: random.Random, kind: str) -> str:
    if kind == "ru_long":
        while True:
            parts = [rng.choice(RU_ADJ), rng.choice(RU_NOUN)]
            if rng.random() < 0.35:
                parts.insert(0, rng.choice(RU_LONG) + ":")
            parts.append(rng.choice(RU_PHRASE))
            t = " ".join(parts)
            if 40 <= len(t) <= 90:
                return t
    if kind == "en":
        return f"The {rng.choice(EN_ADJ)} {rng.choice(EN_NOUN)}: {rng.choice(EN_PHRASE)}"
    if kind == "mixed":
        return f"{rng.choice(RU_ADJ)} {rng.choice(RU_NOUN)} / The {rng.choice(EN_ADJ)} {rng.choice(EN_NOUN)}"
    return rng.choice(RU_SHORT)


def plan(count: int, rng: random.Random) -> list[BookSpec]:
    if count != 60:
        print("note: distribution is tuned for 60 books; scaling proportionally", file=sys.stderr)
    scale = count / 60
    kinds = (["ru_long"] * round(30 * scale) + ["en"] * round(15 * scale)
             + ["mixed"] * round(10 * scale))
    kinds += ["short"] * (count - len(kinds))
    rng.shuffle(kinds)
    covers = (["jpeg"] * round(30 * scale) + ["jpeg_progressive"] * round(10 * scale)
              + ["png"] * round(8 * scale) + ["odd_square"] * round(3 * scale)
              + ["odd_tall"] * round(3 * scale))
    covers += ["none"] * (count - len(covers))
    rng.shuffle(covers)

    authors_ru = [(f"{f} {l}", f"{l}, {f}") for f, l in zip(RU_FIRST, RU_LAST)]
    authors_en = [(f"{f} {l}", f"{l}, {f}") for f, l in zip(EN_FIRST, EN_LAST)]
    all_authors = authors_ru + authors_en  # 15 named authors
    # 5 more spellings to exercise author grouping ("Фамилия Имя" order, initials).
    extra = [(f"{l} {f}", f"{l}, {f}") for f, l in zip(RU_FIRST[:3], RU_LAST[:3])]
    extra += [(f"{f[0]}. {l}", f"{l}, {f[0]}.") for f, l in zip(RU_FIRST[3:5], RU_LAST[3:5])]
    all_authors += extra  # 20 spellings

    specs: list[BookSpec] = []
    used_titles: set[str] = set()
    series_names = ["Хроники маяка", "Northern Archive"]
    for i in range(count):
        kind = kinds[i]
        title = make_title(rng, kind)
        while title in used_titles and kind != "short":
            title = make_title(rng, kind)
        used_titles.add(title)
        lang = "en" if kind == "en" else "ru"
        if i % 12 == 5:  # 5 of 60 without author
            author, file_as = None, None
        else:
            author, file_as = all_authors[i % len(all_authors)]
        spec = BookSpec(index=i + 1, title=title, title_kind=kind, language=lang,
                        author=author, author_file_as=file_as, cover=covers[i],
                        epub_version="3.0" if i % 3 else "2.0")
        if i % 10 in (2, 7):
            spec.series = series_names[i % 2]
            spec.series_index = i // 10 + 1
        if i % 15 == 0:
            spec.chapters = 30
            spec.notes.append("long book (30 chapters)")
        # Filenames: Latin slugs for most, Cyrillic for every 6th (UTF-8 long names).
        if lang == "ru" and i % 6 == 0:
            base = title[:40].rstrip(" :")
            spec.notes.append("cyrillic filename")
        else:
            base = title.lower().translate(TRANSLIT)
        slug = "".join(c if c.isalnum() else "-" for c in base).strip("-")
        while "--" in slug:
            slug = slug.replace("--", "-")
        spec.filename = f"{i + 1:02d}-{slug[:60].strip('-')}.epub"
        spec.identifier = f"urn:uuid:{uuid.UUID(int=rng.getrandbits(128), version=4)}"
        specs.append(spec)
    return specs


# ---------------------------------------------------------------------------
# Content
# ---------------------------------------------------------------------------
def sentence(rng: random.Random, lang: str = "ru") -> str:
    vocab, verbs = (EN_WORDS, EN_VERBS) if lang == "en" else (RU_WORDS, RU_VERBS)
    words = [rng.choice(vocab) for _ in range(rng.randint(5, 12))]
    words.insert(rng.randint(1, len(words) - 1), rng.choice(verbs))
    s = " ".join(words)
    return s[0].upper() + s[1:] + rng.choice([".", ".", ".", "!", "?", "…"])


def chapter_xhtml(rng: random.Random, n: int, lang: str, v3: bool) -> str:
    paras = "\n".join(f"<p>{escape(' '.join(sentence(rng, lang) for _ in range(rng.randint(3, 7))))}</p>"
                      for _ in range(rng.randint(4, 9)))
    ns = ' xmlns:epub="http://www.idpf.org/2007/ops"' if v3 else ""
    doctype = "<!DOCTYPE html>" if v3 else (
        '<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.1//EN" "http://www.w3.org/TR/xhtml11/DTD/xhtml11.dtd">')
    head = "Глава" if lang == "ru" else "Chapter"
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{doctype}\n'
            f'<html xmlns="http://www.w3.org/1999/xhtml"{ns} xml:lang="{lang}" lang="{lang}">\n'
            f'<head><title>{head} {n}</title><link rel="stylesheet" type="text/css" href="style.css"/></head>\n'
            f'<body><h2>{head} {n}</h2>\n{paras}\n</body></html>\n')


def bundled_fonts() -> tuple[str, str]:
    for f in (FONT_BOLD, FONT_REGULAR):
        if not f.is_file():
            sys.exit(f"missing bundled font {f} (expected next to make_corpus.py)")
    return str(FONT_BOLD), str(FONT_REGULAR)


def sha256_file(path: str) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def wrap(draw: ImageDraw.ImageDraw, text: str, font, width: int) -> list[str]:
    lines, cur = [], ""
    for word in text.split():
        trial = f"{cur} {word}".strip()
        if draw.textlength(trial, font=font) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def make_cover(spec: BookSpec, rng: random.Random, fonts: tuple[str | None, str | None]) -> tuple[bytes, str, str]:
    size = {"odd_square": (800, 800), "odd_tall": (500, 1000)}.get(spec.cover, (600, 900))
    w, h = size
    bg = rng.randint(150, 235)
    img = Image.new("L", size, bg)
    d = ImageDraw.Draw(img)
    for _ in range(rng.randint(6, 14)):  # simple generated geometric art
        x0, y0 = rng.randint(-w // 4, w), rng.randint(-h // 4, h)
        r = rng.randint(w // 10, w // 2)
        shade = rng.randint(40, 220)
        if rng.random() < 0.5:
            d.ellipse([x0, y0, x0 + r, y0 + r], outline=shade, width=rng.randint(2, 10))
        else:
            d.rectangle([x0, y0, x0 + r, y0 + r // 2], fill=shade)
    d.rectangle([0, int(h * 0.62), w, h], fill=20)
    bold_path, regular_path = fonts
    if bold_path:
        size_px = max(24, w // 14)
        tf = ImageFont.truetype(bold_path, size_px)
        longest = max(spec.title.split(), key=lambda word: d.textlength(word, font=tf))
        while size_px > 14 and d.textlength(longest, font=tf) > w - 60:
            size_px -= 2  # shrink until the longest word fits the cover width
            tf = ImageFont.truetype(bold_path, size_px)
        af = ImageFont.truetype(regular_path or bold_path, max(18, w // 22))
        y = int(h * 0.65)
        for line in wrap(d, spec.title, tf, w - 60)[:4]:
            d.text((30, y), line, font=tf, fill=245)
            y += int(tf.size * 1.2)
        if spec.author:
            d.text((30, h - af.size - 30), spec.author, font=af, fill=200)
    buf = io.BytesIO()
    if spec.cover == "png":
        img.save(buf, "PNG", optimize=True)
        return buf.getvalue(), "cover.png", "image/png"
    img.convert("RGB").save(buf, "JPEG", quality=85, progressive=(spec.cover == "jpeg_progressive"),
                            optimize=True)
    return buf.getvalue(), "cover.jpg", "image/jpeg"


# ---------------------------------------------------------------------------
# EPUB assembly
# ---------------------------------------------------------------------------
CONTAINER = ('<?xml version="1.0" encoding="UTF-8"?>\n'
             '<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">\n'
             '<rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>'
             '</rootfiles></container>\n')
CSS = "body{margin:0 5%;line-height:1.4}h2{text-align:center;margin:1.5em 0}p{text-indent:1.5em;margin:0}\n"


def build_epub(spec: BookSpec, rng: random.Random, fonts) -> bytes:
    v3 = spec.epub_version == "3.0"
    files: dict[str, tuple[bytes, str]] = {}
    manifest, spine = [], []
    cover_meta = ""
    if spec.cover != "none":
        data, name, mime = make_cover(spec, rng, fonts)
        files[f"OEBPS/{name}"] = (data, mime)
        props = ' properties="cover-image"' if v3 else ""
        manifest.append(f'<item id="cover-img" href="{name}" media-type="{mime}"{props}/>')
        cover_meta = '<meta name="cover" content="cover-img"/>'  # EPUB2-style, also read by most EPUB3 readers
    files["OEBPS/style.css"] = (CSS.encode(), "text/css")
    manifest.append('<item id="css" href="style.css" media-type="text/css"/>')
    for n in range(1, spec.chapters + 1):
        href = f"ch{n:03d}.xhtml"
        files[f"OEBPS/{href}"] = (chapter_xhtml(rng, n, spec.language, v3).encode(), "application/xhtml+xml")
        manifest.append(f'<item id="ch{n}" href="{href}" media-type="application/xhtml+xml"/>')
        spine.append(f'<itemref idref="ch{n}"/>')
    head = "Глава" if spec.language == "ru" else "Chapter"
    # NCX for EPUB2 and as a fallback for EPUB3.
    navpoints = "".join(
        f'<navPoint id="np{n}" playOrder="{n}"><navLabel><text>{head} {n}</text></navLabel>'
        f'<content src="ch{n:03d}.xhtml"/></navPoint>' for n in range(1, spec.chapters + 1))
    ncx = (f'<?xml version="1.0" encoding="UTF-8"?>\n<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">'
           f'<head><meta name="dtb:uid" content="{escape(spec.identifier)}"/></head>'
           f'<docTitle><text>{escape(spec.title)}</text></docTitle><navMap>{navpoints}</navMap></ncx>\n')
    files["OEBPS/toc.ncx"] = (ncx.encode(), "application/x-dtbncx+xml")
    manifest.append('<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>')
    if v3:
        lis = "".join(f'<li><a href="ch{n:03d}.xhtml">{head} {n}</a></li>' for n in range(1, spec.chapters + 1))
        nav = ('<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE html>\n'
               '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">'
               f'<head><title>{escape(spec.title)}</title></head><body>'
               f'<nav epub:type="toc" id="toc"><ol>{lis}</ol></nav></body></html>\n')
        files["OEBPS/nav.xhtml"] = (nav.encode(), "application/xhtml+xml")
        manifest.append('<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>')

    meta = [f'<dc:identifier id="bookid">{escape(spec.identifier)}</dc:identifier>',
            f"<dc:title>{escape(spec.title)}</dc:title>",
            f"<dc:language>{spec.language}</dc:language>"]
    if spec.author:
        if v3:
            meta.append(f'<dc:creator id="a1">{escape(spec.author)}</dc:creator>')
            meta.append(f'<meta refines="#a1" property="file-as">{escape(spec.author_file_as or spec.author)}</meta>')
        else:
            meta.append(f'<dc:creator opf:role="aut" opf:file-as="{escape(spec.author_file_as or spec.author)}">'
                        f"{escape(spec.author)}</dc:creator>")
    if v3:
        meta.append('<meta property="dcterms:modified">2026-11-12T00:00:00Z</meta>')
    if spec.series:
        meta.append(f'<meta name="calibre:series" content="{escape(spec.series)}"/>')
        meta.append(f'<meta name="calibre:series_index" content="{spec.series_index}"/>')
    if cover_meta:
        meta.append(cover_meta)
    opf = (f'<?xml version="1.0" encoding="UTF-8"?>\n'
           f'<package xmlns="http://www.idpf.org/2007/opf" version="{spec.epub_version}" unique-identifier="bookid">'
           f'<metadata xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:opf="http://www.idpf.org/2007/opf">'
           f'{"".join(meta)}</metadata><manifest>{"".join(manifest)}</manifest>'
           f'<spine toc="ncx">{"".join(spine)}</spine></package>\n')

    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        # mimetype must be the first entry and stored uncompressed (OCF requirement).
        z.writestr(zipfile.ZipInfo("mimetype", date_time=(2026, 11, 12, 0, 0, 0)), "application/epub+zip",
                   compress_type=zipfile.ZIP_STORED)
        entries = [("META-INF/container.xml", CONTAINER.encode()), ("OEBPS/content.opf", opf.encode())]
        entries += [(k, v[0]) for k, v in files.items()]
        for name, data in entries:
            info = zipfile.ZipInfo(name, date_time=(2026, 11, 12, 0, 0, 0))
            z.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED)
    return out.getvalue()


# ---------------------------------------------------------------------------
# Self-check (not a replacement for epubcheck)
# ---------------------------------------------------------------------------
def self_check(data: bytes, spec: BookSpec) -> list[str]:
    import xml.etree.ElementTree as ET
    errors = []
    z = zipfile.ZipFile(io.BytesIO(data))
    infos = z.infolist()
    if infos[0].filename != "mimetype" or infos[0].compress_type != zipfile.ZIP_STORED:
        errors.append("mimetype is not the first stored entry")
    ns = {"opf": "http://www.idpf.org/2007/opf", "dc": "http://purl.org/dc/elements/1.1/"}
    root = ET.fromstring(z.read("OEBPS/content.opf"))
    names = set(z.namelist())
    for item in root.find("opf:manifest", ns):
        if f"OEBPS/{item.get('href')}" not in names:
            errors.append(f"missing manifest file {item.get('href')}")
        if item.get("media-type") == "application/xhtml+xml":
            ET.fromstring(z.read(f"OEBPS/{item.get('href')}"))  # well-formed XML
    if root.find("opf:metadata/dc:title", ns).text != spec.title:
        errors.append("title mismatch")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--seed", type=int, default=20261112)
    ap.add_argument("--count", type=int, default=60)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    fonts = bundled_fonts()
    books_dir = args.out / "books"
    books_dir.mkdir(parents=True, exist_ok=True)
    specs = plan(args.count, rng)
    failures = 0
    for spec in specs:
        data = build_epub(spec, random.Random(args.seed * 1000 + spec.index), fonts)
        errs = self_check(data, spec)
        if errs:
            failures += 1
            print(f"{spec.filename}: {errs}", file=sys.stderr)
        (books_dir / spec.filename).write_bytes(data)
        spec.sha256 = hashlib.sha256(data).hexdigest()
        spec.size = len(data)
    manifest = {"generator": "piccoos/tools/corpus/make_corpus.py", "seed": args.seed,
                "count": len(specs), "license": "CC0-1.0 (see LICENSE-CORPUS.md)",
                "environment": {"python": platform.python_version(), "pillow": PIL.__version__,
                                "platform": platform.platform(),
                                "fonts": {Path(f).name: sha256_file(f) for f in fonts}},
                "books": [asdict(s) for s in specs]}
    license_src = Path(__file__).resolve().parent / "LICENSE-CORPUS.md"
    if license_src.is_file():
        (args.out / "LICENSE-CORPUS.md").write_text(license_src.read_text(encoding="utf-8"), encoding="utf-8")
    (args.out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    summary = {}
    for key in ("title_kind", "cover", "epub_version"):
        summary[key] = {}
        for s in specs:
            summary[key][getattr(s, key)] = summary[key].get(getattr(s, key), 0) + 1
    summary["no_author"] = sum(1 for s in specs if not s.author)
    summary["cyrillic_filenames"] = sum(1 for s in specs if "cyrillic filename" in s.notes)
    summary["series"] = sum(1 for s in specs if s.series)
    print(json.dumps(summary, ensure_ascii=False, indent=1))
    print(f"wrote {len(specs)} books to {books_dir}; self-check failures: {failures}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
